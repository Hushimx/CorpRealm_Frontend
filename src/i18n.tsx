export function fill(text: string, vars?: Record<string, string | number>) {
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ''))
}

export function text(key: CopyKey, vars?: Record<string, string | number>) {
  return fill(pack[usePlaySettings.getState().lang][key], vars)
}

export function useT() {
  const lang = usePlaySettings((state) => state.lang)
  return useCallback((key: CopyKey, vars?: Record<string, string | number>) => fill(pack[lang][key], vars), [lang])
}

export function useLocale() {
  const lang = usePlaySettings((state) => state.lang)
  return lang === 'ar' ? 'ar' : 'en'
}

export function knownCopy(text: string, t: (key: CopyKey, vars?: Record<string, string | number>) => string) {
  const key = PLACES[text]
  return key ? t(key) : text
}

export function roomCopy(id: string, fallback: string, t: (key: CopyKey) => string) {
  const key = ROOMS[id]
  return key ? t(key) : fallback
}

export function drawCopy(reason: string, t: (key: CopyKey) => string) {
  const key = DRAW[reason]
  return key ? t(key) : reason
}

export function noteCopy(note: string, t: (key: CopyKey) => string) {
  const key = NOTES[note]
  return key ? t(key) : note
}

export function LanguageSync() {
  const lang = usePlaySettings((state) => state.lang)
  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
  }, [lang])
  return null
}

export function LanguageSwitch({ compact = false }: { compact?: boolean }) {
  const lang = usePlaySettings((state) => state.lang)
  const setLang = usePlaySettings((state) => state.setLang)
  const t = useT()
  return (
    <div className="flex rounded-full bg-frost p-0.5" role="group" aria-label={t('language')}>
      <button type="button" aria-pressed={lang === 'en'} onClick={() => setLang('en')} className={chip(lang === 'en', compact)}>
        {compact ? 'EN' : t('english')}
      </button>
      <button type="button" aria-pressed={lang === 'ar'} onClick={() => setLang('ar')} className={chip(lang === 'ar', compact)}>
        {compact ? 'عربي' : t('arabic')}
      </button>
    </div>
  )
}

function chip(on: boolean, compact: boolean) {
  return ['rounded-full text-xs font-bold', compact ? 'px-2 py-1' : 'px-3 py-1.5', on ? 'bg-ink text-paper' : 'text-ink'].join(' ')
}
